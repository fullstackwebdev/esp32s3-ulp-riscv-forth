/* bridge.c - the P10 bridge model (see bridge.h). Host-only; no libc beyond stdio for snprintf. */
#include <stdio.h>
#include "bridge.h"

#define ESC 0x1D

void br_init(bridge *b)
{
    unsigned i;
    unsigned char *p = (unsigned char *)b;
    for (i = 0; i < sizeof *b; i++) p[i] = 0;   /* deterministic start, incl. counters */
}

unsigned br_cmd_n(const bridge *b) { return b->cmd_n; }

static void cmd_put(bridge *b, int c)
{
    b->cmd[b->cmd_w] = (unsigned char)c;
    b->cmd_w = (b->cmd_w + 1) % CMD_RING;
    b->cmd_n++;
    b->accepted++;
    b->cks_in = b->cks_in * 33u + (unsigned)c;
}

int br_cmd_get(bridge *b)
{
    int c;
    if (!b->cmd_n) return -1;
    c = b->cmd[b->cmd_r];
    b->cmd_r = (b->cmd_r + 1) % CMD_RING;
    b->cmd_n--;
    b->cks_out = b->cks_out * 33u + (unsigned)c;
    return c;
}

void br_out_put(bridge *b, int c)
{
    /* GUARDRAIL: the output ring must never wrap and overwrite unread bytes — an overwrite is a
     * silent byte loss that shows up as a garbled line much later. When it is full, block the
     * producer path here (pl_emit) and count the drop instead of corrupting the stream. */
    if (b->out_n >= OUT_RING) { b->dropped++; return; }
    b->out[b->out_w] = (unsigned char)c;
    b->out_w = (b->out_w + 1) % OUT_RING;
    b->out_n++;
}

int br_out_get(bridge *b)
{
    int c;
    if (!b->out_n) return -1;
    c = b->out[b->out_r];
    b->out_r = (b->out_r + 1) % OUT_RING;
    b->out_n--;
    return c;
}

void br_state_line(bridge *b, char *dst, unsigned cap)
{
    snprintf(dst, cap, "mode=%s cmd=%u/%u out=%u/%u drops=%u xoff=%u%s accepted=%u refused=%u\n",
             b->mode == BR_FRAMED ? "framed" : "passthrough",
             b->cmd_n, (unsigned)CMD_RING, b->out_n, (unsigned)OUT_RING,
             b->dropped, b->xoff, b->xoff ? " XOFF" : "", b->accepted, b->refused);
}

/* Resolve a 0x1D that is followed by `c`. Returns 0 when the sequence needs more ring room than
 * is available (the caller then reports XOFF and leaves both bytes un-consumed). */
static int esc_resolve(bridge *b, int c)
{
    b->esc = 0;
    if (c == ESC) { b->esc_literal++; cmd_put(b, ESC); return 1; }
    if (c == 'f') { b->esc_mode++; b->mode = BR_FRAMED;      return 1; }
    if (c == 'p') { b->esc_mode++; b->mode = BR_PASSTHROUGH; return 1; }
    if (c == 'q') { b->esc_quit++; b->quit = 1;              return 1; }
    if (c == 's') {
        char line[160];
        b->esc_state++;
        br_state_line(b, line, sizeof line);
        /* the state line is generated by the bridge and travels on the console stream, so the
         * ULP input buffer is untouched: nothing reaches cmd[] */
        { unsigned i; for (i = 0; line[i]; i++) br_out_put(b, line[i]); }
        return 1;
    }
    /* GUARDRAIL: an unknown escape must pass through BOTH bytes verbatim. The first draft returned
     * without re-emitting the 0x1D, so a typo like ESC-x silently ate a character — the one failure
     * mode 06-repl.md section 3 promises cannot happen. Recognise-or-pass-through, never consume
     * on a miss. */
    b->esc_unknown++;
    if (b->cmd_n + 2 > CMD_RING) { b->esc = 1; b->refused++; return 0; }
    cmd_put(b, ESC);
    cmd_put(b, c);
    return 1;
}

unsigned br_feed(bridge *b, const unsigned char *buf, unsigned n)
{
    unsigned used = 0;
    int progressed;
    while (used < n) {
        int c = buf[used];
        /* XOFF water mark: above 75 % occupancy the bridge stops reading the port */
        if (b->cmd_n >= XOFF_WM) {
            b->xoff = 1;
            b->refused += n - used;
            return used;
        }
        b->xoff = 0;
        if (b->esc) {
            progressed = esc_resolve(b, c);
            if (!progressed) { b->xoff = 1; return used; }
            used++;
            continue;
        }
        if (c == ESC) { b->esc = 1; used++; continue; }   /* one byte of lookahead */
        cmd_put(b, c);
        used++;
    }
    return used;
}

void br_idle(bridge *b)
{
    /* The bound: one poll. The bridge holds one byte of lookahead and flushes it as a literal on
     * the first poll in which the source is empty, so a trailing 0x1D waits at most one poll
     * (one byte time on the wire plus one bridge tick), never forever. */
    if (!b->esc) return;
    b->esc = 0;
    b->esc_literal++;
    cmd_put(b, ESC);
}
