"""gen_aes_vectors.py - emit the AES-128 test vector the board is judged against.

Two authorities, no memory:

  * the 44 round keys come from the FIPS-197 key schedule, and the schedule is
    validated against the PUBLISHED A.1 expansion (a0fafe17 88542cb1 ...) before
    it is used for anything;
  * the ciphertext comes from `openssl enc -aes-128-ecb`.

GUARDRAIL: this generator exists because every remembered value was wrong. While
writing the cipher I "knew" that key 000102..0f expands to a0fafe17 - that value
belongs to FIPS-197's OTHER example key (2b7e1516...). The board would have
printed a valid-looking ciphertext for a key nobody asked for, and the test would
have passed. Generate, then compare.
"""
import json
import pathlib
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
TESTS = HERE.parent / "tests" / "data"   # GUARDRAIL: a LOADED file, not a demo transcript - tests/run.sh globs tests/*.fs and demands a .expected for each

FIPS_A1_KEY = "2b7e151628aed2a6abf7158809cf4f3c"
FIPS_A1_W4 = ["a0fafe17", "88542cb1", "23a33939", "2a6c7605"]
KEY = "000102030405060708090a0b0c0d0e0f"
PLAIN = "00112233445566778899aabbccddeeff"


def gmul(a, b):
    p = 0
    for _ in range(8):
        if b & 1:
            p ^= a
        hi = a & 0x80
        a = (a << 1) & 0xff
        if hi:
            a ^= 0x1b
        b >>= 1
    return p


def sbox():
    inv = [0] * 256
    for x in range(1, 256):
        for y in range(1, 256):
            if gmul(x, y) == 1:
                inv[x] = y
                break
    rotl = lambda b, n: ((b << n) | (b >> (8 - n))) & 0xff
    return [inv[x] ^ rotl(inv[x], 1) ^ rotl(inv[x], 2) ^ rotl(inv[x], 3)
            ^ rotl(inv[x], 4) ^ 0x63 for x in range(256)]


def schedule(key_hex, SB):
    key = bytes.fromhex(key_hex)
    w = [list(key[4 * i:4 * i + 4]) for i in range(4)]
    rcon = [0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36]
    for i in range(4, 44):
        t = list(w[i - 1])
        if i % 4 == 0:
            t = [SB[b] for b in t[1:] + t[:1]]
            t[0] ^= rcon[i // 4 - 1]
        w.append([a ^ b for a, b in zip(w[i - 4], t)])
    return b"".join(bytes(x) for x in w)


def wrap(tokens, width=63):
    lines, cur = [], ""
    for t in tokens:
        cur = t if not cur else (cur + " " + t if len(cur) + 1 + len(t) <= width else (lines.append(cur), t)[1])
    if cur:
        lines.append(cur)
    return lines


def comment(text, width=61):
    return wrap(text.split(), width)


def openssl_ct(key_hex, plain_hex):
    tmp = HERE / ".aes_pt.bin"
    tmp.write_bytes(bytes.fromhex(plain_hex))
    try:
        out = subprocess.run(["openssl", "enc", "-aes-128-ecb", "-K", key_hex, "-nopad",
                              "-in", str(tmp)], capture_output=True, check=True).stdout
    finally:
        tmp.unlink()
    return out.hex()


def main():
    SB = sbox()
    assert SB[:4] == [0x63, 0x7C, 0x77, 0x7B], "S-box does not match FIPS-197"
    probe = schedule(FIPS_A1_KEY, SB)
    got = [f"{int.from_bytes(probe[16 + 4 * i:20 + 4 * i], 'big'):08x}" for i in range(4)]
    if got != FIPS_A1_W4:
        print(f"FAIL key schedule: w4..w7 = {got}, FIPS-197 A.1 says {FIPS_A1_W4}", file=sys.stderr)
        return 1
    rk = schedule(KEY, SB)
    ct = openssl_ct(KEY, PLAIN)
    pt = bytes.fromhex(PLAIN)

    lines = [f"\\ {t}" for t in comment(
        "lora_aes_vectors.fs - AES-128 vector: schedule from FIPS-197, ciphertext from openssl. "
        "Generated by tools/gen_aes_vectors.py; do not edit by hand.")]
    lines += [""] + [f"\\ {t}" for t in comment(f"Load AFTER lora_aes.fs. Key {KEY}.")]
    lines += [f"\\ {t}" for t in comment(
        "The 44 round keys go straight into W, so the CIPHER is tested without the schedule phase "
        "(measured: they do not fit the dictionary together).")]
    lines += [f"\\ {t}" for t in comment(
        "GUARDRAIL: this file defines NOTHING. The cipher leaves 12 B free (measured) and two helper "
        "definitions cost 20 B, which answered ERR_DICT; ST then stayed zero and the test compared "
        "zeros against the vector.")]
    lines += [f"\\ {t}" for t in comment(
        "GUARDRAIL: bytes go in with C!, not with a 32-bit `!` of a big decimal. Measured: 2291784379 "
        "(0x8899AABB) came back as -77665545, so the stream was not the one the vector names.")]
    lines += [""]
    for o in range(0, 176, 8):
        lines += wrap([f"{b} {o + i} W + C!" for i, b in enumerate(rk[o:o + 8])])
    lines += [""] + [f"\\ {t}" for t in comment(f"plaintext = {PLAIN}")]
    for o in range(0, 16, 8):
        lines += wrap([f"{b} {o + i} ST + C!" for i, b in enumerate(pt[o:o + 8])])
    lines += [""] + [f"\\ ciphertext = {ct}"]
    longest = max(len(l) for l in lines)
    if longest > 63:
        print(f"FAIL a generated line is {longest} B; the ring holds 63", file=sys.stderr)
        return 1
    (TESTS / "lora_aes_vectors.fs").write_text("\n".join(lines) + "\n")

    # ---- the CTR keystream: openssl's CTR ciphertext XOR the plaintext
    iv = "00" * 16
    tmp = HERE / ".aes_pt.bin"
    tmp.write_bytes(bytes.fromhex(PLAIN))
    try:
        ctr = subprocess.run(["openssl", "enc", "-aes-128-ctr", "-K", KEY, "-iv", iv, "-nopad",
                              "-in", str(tmp)], capture_output=True, check=True).stdout
    finally:
        tmp.unlink()
    ks = bytes(a ^ b for a, b in zip(ctr, pt))
    lines = [f"\\ {x}" for x in comment(
        "lora_ctr_vectors.fs - the CTR keystream: ST = counter block (all zero), run AESB, read ST. "
        "Generated by tools/gen_aes_vectors.py from openssl enc -aes-128-ctr.")]
    lines += [""] + [f"\\ {x}" for x in comment(
        "GUARDRAIL: defines nothing and needs no XOR word - the cipher leaves 0 B free (measured), so the "
        "keystream is compared as a block.")]
    lines += [""]
    for o in range(0, 16, 8):
        lines += wrap([f"0 {o + i} ST + C!" for i in range(8)])
    lines += [""] + [f"\\ keystream = {ks.hex()}"]
    if max(len(l) for l in lines) > 63:
        print("FAIL ctr vector line too long", file=sys.stderr)
        return 1
    (TESTS / "lora_ctr_vectors.fs").write_text("\n".join(lines) + "\n")

    ints = lambda b: [int.from_bytes(b[4 * i:4 * i + 4], "big") for i in range(4)]
    (TESTS / "lora_aes_vector.json").write_text(json.dumps(
        {"W": ints(rk), "PT": ints(pt), "CT": ints(bytes.fromhex(ct)), "cthex": ct,
         "keystream_hex": ks.hex(), "ctr_cthex": ctr.hex()}, indent=0))
    print(f"wrote lora_aes_vectors.fs ({longest} B longest) + lora_ctr_vectors.fs (keystream) + .json")
    print(f"  key {KEY} -> ciphertext {ct}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
