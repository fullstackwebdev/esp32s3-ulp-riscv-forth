\ loratx.fs - RADIO-INIT + a Meshtastic-shaped frame, as ONE
\ PHASE.
\
\ WHY A PHASE: it is loaded into the pool on its own and costs
\ the app nothing while it is not running. Measured: the
\ bring-up alone is 779 B as a phase and 491 B of code inside
\ an app; this file adds the frame.
\
\ WHAT IT SENDS: 16-byte Meshtastic PacketHeader + protobuf
\ Data. header to4/from4/id4/flags/channel/next_hop/relay = 16
\ B Data   = 08 <portnum varint> 12 <len> <payload> Our frame
\ is 26 B: 16 header + 10 Data (portnum 256, payload "hello").
\ The wire format is from docs/31, fetched once and hashed, not
\ recalled.
\
\ WHAT IT DOES NOT DO: encrypt. Meshtastic's channel path is
\ AES-CTR and the cipher is 1328 B - it fills the whole prompt
\ dictionary exactly and a phase window is 999 B, so the cipher
\ cannot live here (measured, and registry cells are resident
\ so they shrink the window rather than holding data). This
\ phase defines where the ciphertext would go: the Data payload
\ region, bytes 18..21 of the frame.
\
\ GUARDRAIL: a phase cannot see another phase's words
\ (measured: a phase calling a neighbour's DRAW is refused BY
\ NAME), so the primitives are duplicated here on purpose.
\ Duplication is the price of chaining.
\
\ GUARDRAIL: the frame is DATA, one `C,` per wire byte, because
\ a table of 26 bytes costs 26 B and the same bytes written by
\ code cost ~40 tokens. Same argument as the configuration
\ table below.
\
\ GUARDRAIL: every line stays under 63 B - the input ring drops
\ longer lines SILENTLY and the definition then does not exist.
\
\ GUARDRAIL: `C,` bytes must leave HERE EVEN at EVERY
\ definition boundary, not merely in total: four 1-byte cells
\ summed even, HERE was odd at each CREATE, and forty
\ definitions were refused with ERR_DICT.
\
\ CONFIG: STDBY_RC, DC-DC, TCXO 1.8 V on DIO3 + 5 ms, calibrate
\ all, DIO2 as RF switch, LoRa, 868.1 MHz, image cal 863-870,
\ PA 14 dBm, buffer base 0, SF9 / BW125 / CR4-5 / LDRO 0,
\ preamble 16 (Meshtastic's preset; our older driver used 8),
\ explicit header, length 26, CRC on, all IRQ sources enabled.
\
\ Pads: NSS 8, SCK 9, MOSI 10, MISO 11, RESET 12, BUSY 13. The
\ register numbers are the ALIAS WINDOW (RTCIO 41984 = 0xA400),
\ never the SoC map: the coprocessor does not decode it.

: PIN! ( level pin -- )
  10 + 1 SWAP LSHIFT SWAP IF 41988 ELSE 41992 THEN ! ;
: PIN@ ( pin -- level )
  10 + 1 SWAP LSHIFT 42020 @ AND 0= 0= ;
: BUSY-LOW ( -- )
  200 BEGIN 1- 1 MS DUP 0= 13 PIN@ 0= OR UNTIL DROP ;
: NSSLO ( -- ) BUSY-LOW 0 8 PIN! ;
: NSSHI ( -- ) 1 8 PIN! ;
: BITOUT ( b -- b*2 )
  DUP 128 AND IF 1 10 PIN! ELSE 0 10 PIN! THEN
  1 9 PIN! 0 9 PIN! 2 * ;
: BITREAD ( b -- b' )
  2 * 1 9 PIN! 11 PIN@ 0 9 PIN! IF 1 + THEN ;
: >BYTE ( b -- )
  BITOUT BITOUT BITOUT BITOUT
  BITOUT BITOUT BITOUT BITOUT DROP ;
: RD-BYTE ( -- b ) 0 BITREAD BITREAD BITREAD BITREAD
  BITREAD BITREAD BITREAD BITREAD ;
: RD2 ( -- w ) RD-BYTE 8 LSHIFT RD-BYTE OR ;
: INEN ( padreg -- )
  DUP @ 8192 OR 393216 INVERT AND SWAP ! ;
