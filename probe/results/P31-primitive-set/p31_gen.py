#!/usr/bin/env python3
"""P31: split the shipping engine's primitive table and dispatch switch into guarded includes.

One source, two levers:
  * src/p31_prims.inc  — the PRIMS X() list, one entry per line, each behind
                         `#if !defined(P31_SUBSET) || defined(P_HAVE_<ID>)`
  * src/p31_cases.inc  — the switch's case groups, each behind the same guard shape

With no -DP31_SUBSET every entry and every case is compiled, so the variant-A token stream is
byte-identical to P29/P30's and the 4934 B bar is still a real bar.

The text is *moved*, never retyped: the generator cuts the entries and the case groups out of
uforth.c and writes them back verbatim inside the guards.

GUARDRAIL: the case groups that share one body (`case P_LOOP: case P_PLOOP:` and
`case P_TICK: case P_BTICK:`) must be enabled together — the body branches on `cf`, and a
half-enabled group either loses a case label the body tests for or drops the test. The generator
refuses a partial group instead of emitting code that compiles and dispatches wrongly.
"""
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent
src = root / "src" / "uforth.c"
text = src.read_text()

# ---- 1. the PRIMS macro -> p31_prims.inc -------------------------------------------------
m = re.search(r"#define PRIMS \\\n(.*?)\n\n", text, re.S)
if not m:
    sys.exit("cannot find the PRIMS macro")
body = m.group(1)
entries = re.findall(r"X\((\w+),\s*\"((?:[^\"\\]|\\.)*)\",\s*(\d)\)", body)
if len(entries) < 55:
    sys.exit(f"only {len(entries)} primitive entries parsed — the regex lost some")
prims_inc = ["/* P31: generated by p31_gen.py from uforth.c's PRIMS macro. One entry per line so each",
             " * primitive can be dropped by ID; order is the original, so the enum's token values and",
             " * therefore variant A's code are unchanged. */"]
for pid, name, imm in entries:
    prims_inc.append(f"#if !defined(P31_SUBSET) || defined(P_HAVE_{pid})")
    prims_inc.append(f'X({pid},"{name}",{imm})')
    prims_inc.append("#endif")
prims_inc = "\n".join(prims_inc) + "\n"
(root / "src" / "p31_prims.inc").write_text(prims_inc)

# ---- 2. the dispatch switch -> p31_cases.inc ---------------------------------------------
start = text.index("        switch (cf) {")
i = text.index("\n", start)
depth = text.index("{", start)
j = depth
d = 0
while True:
    if text[j] == "{":
        d += 1
    elif text[j] == "}":
        d -= 1
        if d == 0:
            break
    j += 1
block = text[i:j]                       # the switch body, without `switch (cf) {` / closing brace

lines = block.split("\n")
# drop the P30 out-of-line preprocessor branch: P31 builds the inlined shape only, and the
# `#else` half is exactly what variant A compiles anyway.
if "#if defined(P30_OUTOFLINE)" not in block:
    sys.exit("expected the P30 out-of-line branch in the switch")
a = next(k for k, l in enumerate(lines) if l.startswith("#if defined(P30_OUTOFLINE)"))
b = next(k for k in range(a, len(lines)) if lines[k].startswith("#else"))
c = next(k for k in range(b, len(lines)) if lines[k].startswith("#endif"))
lines = lines[:a] + lines[b + 1:c] + lines[c + 1:]

# group the remaining lines by `case` label
groups = []
for ln in lines:
    mm = re.match(r"^(\s*case (P_\w+):)(.*)$", ln)
    if mm:
        groups.append({"ids": [mm.group(2)[2:]], "lines": [ln]})   # P_XXX -> XXX, same key as PRIMS
    elif groups:
        groups[-1]["lines"].append(ln)
    else:
        groups.append({"ids": [], "lines": [ln]})        # prologue (blank line)

# strip trailing blank lines of the block into the prologue so the guard fits tightly
cases_inc = ["/* P31: generated by p31_gen.py from uforth.c's dispatch switch. The case bodies are cut",
             " * verbatim — retyping them would make the variant comparison a comparison of two",
             " * different machines (P30's lesson). */"]
GROUPED = {"PLOOP": "LOOP", "BTICK": "TICK"}   # bodies that branch on cf: enable together
for g in groups:
    if not g["ids"]:
        cases_inc.extend(g["lines"])
        continue
    guard = " || ".join(f"defined(P_HAVE_{GROUPED.get(x, x)})" for x in g["ids"])
    cases_inc.append(f"#if !defined(P31_SUBSET) || {guard}")
    cases_inc.extend(g["lines"])
    cases_inc.append("#endif")
cases_inc = "\n".join(cases_inc) + "\n"
(root / "src" / "p31_cases.inc").write_text(cases_inc)

# ---- 3. rewrite uforth.c to include them -------------------------------------------------
new = text[:start] + '        switch (cf) {\n#include "p31_cases.inc"\n        }' + text[j + 1:]
new = new.replace(m.group(0), "#define PRIMS P31_PRIMS_LIST_IS_AN_INCLUDE\n", 1) if False else new
# the macro definition itself goes away; both uses become the include
new = new.replace(m.group(0), "", 1)
new = new.replace("PRIMS\n#undef X", '#include "p31_prims.inc"\n#undef X', 1)
new = new.replace("    PRIMS\n#undef X", '    #include "p31_prims.inc"\n#undef X', 1)
if new.count("p31_prims.inc") != 2:
    sys.exit(f"expected 2 includes of the prim list, found {new.count('p31_prims.inc')}")
src.write_text(new)
print(f"prims: {len(entries)} entries; cases: {sum(1 for g in groups if g['ids'])} groups")
print("droppable-by-name:", " ".join(sorted(GROUPED.get(x, x) for g in groups for x in g["ids"])))
