#!/usr/bin/env python3
"""tokcensus.py — count the tokens in a baked image, statically, from the image itself.

    ./tools/tokcensus.py out/image.h out/names.log

# GUARDRAIL: this tool is the reason the P54 token idea could be rejected in an hour instead of a week —
# the prize ("1-byte codes save 150-200 B") is a STATIC count, and nothing but a walk of the real image
# can produce it. Any budget for a code-area change must be quoted from here, never from a token count
# in a comment or a `#define`.
#
# Why this exists: "how many tokens would a 1-byte code shrink?" is the whole premise of P54's
variable-length-token idea, and a number typed from memory is not a measurement. This walks
mem[] as the *engine* walks it — per definition, with the operand widths the dispatch switch
actually uses — so a token is counted only if the machine would execute it as one.

The xt->name map comes from the bake itself (`-DP54_NAMES` prints one NAME line per header from
mkhdr_pad, the one place a name becomes a header). Parsing the prelude with a regex would be a
second derivation of the same vocabulary (R6) and a missed name is a token this tool silently
miscounts.

Layout facts it uses, all of them from src/uforth.c, none of them retyped:
  * mem[V_HERE(4) .. V_LATEST(8)) is the code area (headers count DOWN from HDRTOP);
  * a word's xt is the offset of its 2-byte code field in the code area;
  * the code field selects what follows: DOCOL(0) a token stream, DOVAR(1)/DOCON(2) a 4-aligned
    data cell, anything else a bare primitive body with no inline data;
  * within a token stream, LIT(4) is followed by a 4-byte cell, BRANCH(5)/ZBRANCH(6)/LOOP(8)/
    PLOOP(9) by a 2-byte operand cell, PDOTQ(56) by a counted string padded to even, and DO(7)
    by nothing.

It fails loud on anything it does not recognise: a decoder that guesses would report a token
count for a stream the engine cannot run.
"""
import re
import sys
from collections import Counter

DICT = 56                       # uforth.c: DICT = 56, the first byte of the code area
P_DOCOL, P_DOVAR, P_DOCON = 0, 1, 2
P_LIT, P_BRANCH, P_ZBRANCH, P_DO = 4, 5, 6, 7
P_LOOP, P_PLOOP = 8, 9
P_PDOTQ = 56
OPERAND_2 = (P_BRANCH, P_ZBRANCH, P_LOOP, P_PLOOP)


def die(msg):
    sys.exit(f"tokcensus: {msg}")


def parse_image(path):
    txt = open(path).read()
    m = re.search(r"generated by uforth -d: (\d+) of (\d+) bytes used", txt)
    if not m:
        die(f"{path}: no 'generated by uforth -d' header line — not a bake dump")
    span, memsz = int(m.group(1)), int(m.group(2))
    data = bytes(int(v, 16) for v in re.findall(r"0x([0-9a-f]{2})", txt[txt.index("{"):]))
    if len(data) != span:
        die(f"{path}: header says {span} bytes, dump holds {len(data)}")
    if span > memsz:
        die(f"{path}: dump {span} > MEMSZ {memsz}")
    return data, span, memsz


def u16(d, a):
    return d[a] | d[a + 1] << 8


def u32(d, a):
    return d[a] | d[a + 1] << 8 | d[a + 2] << 16 | d[a + 3] << 24


def parse_names(path):
    names = {}
    for line in open(path):
        if not line.startswith("NAME "):
            continue
        m = re.match(r"NAME xt=(\d+) cf=(\d+) imm=(\d+) (.*)\n?$", line)
        if not m:
            die(f"{path}: unparsable NAME line: {line!r}")
        xt = int(m.group(1))
        if xt in names:
            die(f"{path}: xt {xt} defined twice ({names[xt]['name']} / {m.group(4)})")
        names[xt] = {"cf": int(m.group(2)), "imm": int(m.group(3)), "name": m.group(4)}
    if not names:
        die(f"{path}: no NAME lines — was the bake built with -DP54_NAMES?")
    return names


def main():
    if len(sys.argv) != 3:
        die(__doc__)
    img, names = sys.argv[1], parse_names(sys.argv[2])
    d, hdrtop, memsz = parse_image(img)

    here, latest = u32(d, 4), u32(d, 8)
    if not (DICT <= here <= latest <= hdrtop):
        die(f"layout nonsense: DICT {DICT} here {here} latest {latest} hdrtop {hdrtop}")

    # --- the dictionary: one 4-byte key per entry, growing down from HDRTOP -----------------
    hdrs, flagged = {}, []
    for h in range(latest, hdrtop, 4):
        key = u32(d, h)
        xt, imm = (key >> 1) & 0x7FF, key & 1
        if xt not in names:
            die(f"header at {h} names xt {xt}, which the bake never created")
        # imm is NOT compared with the bake's: IMMEDIATE is a Forth word that sets bit 0 of the
        # 4-byte key *after* the header exists, so the log records creation time and the image
        # records the end state. Reported below instead of asserted.
        if imm:
            flagged.append(names[xt]["name"])
        if u16(d, xt) != names[xt]["cf"]:
            die(f"xt {xt} ({names[xt]['name']}): code field in image is {u16(d, xt)}, "
                f"bake said {names[xt]['cf']} — image and name log are different bakes")
        if xt in hdrs:
            die(f"xt {xt} carries two headers")
        hdrs[xt] = h
    if len(hdrs) != len(names):
        die(f"dictionary holds {len(hdrs)} headers, the bake created {len(names)} words")
    if (hdrtop - latest) % 4:
        die(f"header span {hdrtop - latest} is not a whole number of 4-byte entries")

    # --- walk the code area, definition by definition --------------------------------------
    # regions[(addr, width)] = kind, so the byte accounting can be closed exactly.
    regions, toks = [], []      # toks: (address, target xt, target name, emitted_by)
    word = [0, 0]               # marks so far for the word being walked: [addr, bytes]
    def mark(addr, width, kind, label):
        regions.append((addr, width, kind, label))
        word[1] += width

    xts = sorted(hdrs)
    for i, xt in enumerate(xts):
        end = xts[i + 1] if i + 1 < len(xts) else here
        cf, name = u16(d, xt), names[xt]["name"]
        word[1] = 0
        mark(xt, 2, "code-field", name)
        p = xt + 2
        if cf == P_DOCOL:
            while p + 2 <= end:
                t = u16(d, p)
                if t not in names:
                    die(f"{name} (xt {xt}): token {t} at {p} is not a known xt")
                tname, tcf = names[t]["name"], names[t]["cf"]
                # A raw 2-byte cell from the prelude's `W,` reads back as the xt itself, so the
                # census cannot tell a W,-emitted token from a cw()-emitted one by decoding.
                # It does not have to: BRANCH/0BRANCH are emitted ONLY by the immediate words
                # (IF/ELSE/WHILE/REPEAT/UNTIL) via W,, and nothing else ever emits them.
                by = "W," if tcf in (P_BRANCH, P_ZBRANCH) else "cw"
                toks.append((p, t, tname, by))
                mark(p, 2, "token", tname)
                p += 2
                if tcf == P_LIT:
                    mark(p, 4, "operand", "LIT cell")
                    p += 4
                elif tcf in OPERAND_2:
                    mark(p, 2, "operand", tname + " target")
                    p += 2
                elif tcf == P_PDOTQ:
                    n = d[p]
                    mark(p, (n + 2) & ~1, "operand", f"{n} B counted string")
                    p += (n + 2) & ~1
            if p != end:
                die(f"{name} (xt {xt}): body ends at {p}, next definition at {end}")
        elif cf in (P_DOVAR, P_DOCON):
            q = (xt + 2 + 3) & ~3
            while q + 2 <= end:
                mark(q, 2, "data", name + " cell")
                q += 2
            if cf == P_DOCON and end != ((xt + 2 + 3) & ~3) + 4:
                die(f"{name}: DOCON owns {end - ((xt + 2 + 3) & ~3)} B of data, expected 4")
            pass
        else:
            # A word whose code field is a primitive owns exactly its code field: the counted string
            # that `(.")` reads belongs to a *token* for it in someone else's body, never to the
            # primitive's own definition. Marking a string here re-counted 60 B that do not exist.
            if end != xt + 2:
                die(f"primitive {name} (xt {xt}) owns {end - xt} B, only a code field was expected")
        if word[1] != end - xt:
            die(f"{name} (xt {xt}): marks describe {word[1]} B of a {end - xt} B definition")
        if word[1] != end - xt:
            die(f"{name} (xt {xt}): marks describe {word[1]} B of a {end - xt} B definition")

    # --- report ---------------------------------------------------------------------------
    covered = sum(w for _, w, _, _ in regions)
    by_kind = Counter()
    for _, w, kind, _ in regions:
        by_kind[kind] += w
    print(f"image {img}: MEMSZ {memsz}, code area {here} B [DICT {DICT}..{here}), "
          f"V_LATEST {latest}, HDRTOP {hdrtop}")
    print(f"words {len(names)} (immediate: {len(flagged)}), code-area bytes {covered} of {here - DICT}: "
          + ", ".join(f"{k} {v} B" for k, v in sorted(by_kind.items())))
    if covered != here - DICT:
        die(f"walk covers {covered} B, the code area is {here - DICT} B — the walk is wrong")
    for addr, w, kind, label in regions:
        if addr & 1 or w & 1:
            die(f"{kind} {label} at {addr} is odd-sized ({w} B) — a 2-byte token image must not be")

    # two candidate meanings for a 1-byte code
    #
    # scheme A  code = primitive id. The target must be a primitive that does not need `w`
    #           (ct != DOCOL/DOVAR/DOCON), because a code byte carries no xt.
    # scheme B  code = (xt - DICT)/2, valid while xt < DICT+256: any word, colon words included,
    #           because w stays reconstructible as DICT + 2*code.
    a = [t for t in toks if names[t[1]]["cf"] not in (P_DOCOL, P_DOVAR, P_DOCON)]
    b = [t for t in toks if t[1] - DICT < 256]
    print(f"tokens {len(toks)}: emitted by cw() {len([t for t in toks if t[3] == 'cw'])}, "
          f"by the prelude's W, (BRANCH/0BRANCH) {len([t for t in toks if t[3] == 'W,'])}")

    print("\ntoken frequency over the whole baked code area (hottest first):")
    freq = Counter(t[2] for t in toks)
    for name, n in freq.most_common():
        print(f"  {name:12s} {n:3d}")
    print(f"  distinct token targets: {len(freq)} of {len(names)} words")
    hot_rows = [(n, w) for w, n in freq.items()][:0]

    print(f"\nscheme A (code = primitive id)            : {len(a):3d} of {len(toks)} tokens, "
          f"best case {len(a)} B saved")
    print(f"scheme B (code = code-area halfword index): {len(b):3d} of {len(toks)} tokens, "
          f"best case {len(b)} B saved")
    print(f"   of scheme B, reachable only through the prelude's W,: "
          f"{len([t for t in b if t[3] == 'W,'])} (those need a Forth-side token emitter)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
