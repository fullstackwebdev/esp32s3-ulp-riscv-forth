#!/usr/bin/env python3
"""P31: five variants of the P29 shipping engine, each measured the same way.

Recipe: P29's (P12/P20's stub-subtraction build). IDF's own generated compile/link flags, so the same
compiler, -march, startup and peripherals script as P20 — only the engine TU and ram LENGTH change.

One run per variant:  python3 p31_build.py <variant A..E> [memsz]

Variant defines (all in src/uforth.c, one source, no copies):
  A  nothing                       — P29 baseline, must reproduce engine 4934 exactly
  B  -DP31_NOINLINE                — resolve/pg_load/rd16_paged out of line
  C  B + -DP30_HANDCOPY            — hand-written VM copy and task zeroing (no libgcc memcpy/memset)
  D  C + the eight primitives a programmer needs (P32): I J UNLOOP GPIO! ' CONSTANT ( ."
GUARDRAIL: D is C plus restores only — the same source, the same flags, the same script. A "richer" D
built from a freshly written uforth.c would price a different machine and tell nobody anything (P31).

GUARDRAIL: the engine is measured as `.bin − control` and, separately, the real 7856 B link is attempted
so "fits 3438" is a link result and not an arithmetic guess; a variant is only measurable at all because
the diagnostic script (LENGTH 12000) places an over-budget image. Using the diag script for the budget
verdict would report a fit no real link gives.
"""
import json, pathlib, re, shlex, subprocess, sys

root = pathlib.Path(__file__).resolve().parent
src = root / "src"
art = root / "artifacts"
p20 = root.parent / "P20-native-accessors" / "idfproj/build/esp-idf/main/ulp_main"
p29 = root.parent / "P29-shipping-engine"

# GUARDRAIL: the required set is read from src/p31_required.defs, generated by derive.py from what the
# layer and prelude actually name — never typed by hand, or B is a guess with a build attached (P31).
req = [l.strip() for l in (root / "src" / "p31_required.defs").read_text().split() if l.strip()]
# GUARDRAIL: (.") comes with ." — `.""` in compile state compiles the (.") token and V_XSTR dispatch;
# restoring DOTQ without PDOTQ leaves compiled strings as a token with no case body, i.e. a silent
# wrong answer instead of a printed string (P32).
RESTORED = ["-DP_HAVE_I", "-DP_HAVE_J", "-DP_HAVE_UNLOOP", "-DP_HAVE_GPIOS", "-DP_HAVE_TICK",
            "-DP_HAVE_CONSTANT", "-DP_HAVE_PAREN", "-DP_HAVE_DOTQ", "-DP_HAVE_PDOTQ"]
VARIANTS = {
    "A": [],                                          # P29 baseline 61 — must reproduce 4934
    "B": ["-DP31_SUBSET"] + req,                      # exactly the required set, A's shape
    "C": ["-DP31_SUBSET"] + req + ["-DP30_HANDCOPY"], # B + P30 D's hand VM copy and unrolled zeroing
    "D": ["-DP31_SUBSET"] + req + ["-DP30_HANDCOPY"] + RESTORED,  # P32: C + the language back
}

cc = json.load(open(p20 / "compile_commands.json"))
stub_cc = next(e for e in cc if e["file"].endswith("ulp_stubs.c"))
args = shlex.split(stub_cc["command"])
gcc = args[0]
ninja = (p20 / "build.ninja").read_text()
link_flags = re.search(r"^  LINK_FLAGS = (.*)$", ninja, re.M).group(1)
objs = re.search(r"^build ulp_main\.elf: \S+ (.*?)(?: \|\| ld_script)$", ninja, re.M).group(1).split()
objs = [str((p20 / o).resolve()) for o in objs]
stub_obj = next(o for o in objs if o.endswith("ulp_stubs.c.obj"))
rest = [o for o in objs if o != stub_obj]


def compile_stub(out, extra):
    # GUARDRAIL: the source path appears twice in the IDF compile command (input and after -c);
    # rewriting only one makes gcc see two inputs and die with "cannot specify -o with multiple files".
    a = [str(src / "ulp_stubs.c") if x.endswith("ulp_stubs.c") else x for x in args]
    a[a.index("-o") + 1] = str(out)
    a += extra
    print("+ cc", out.name, extra, file=sys.stderr)
    subprocess.run(a, check=True)


def link(out, obj, ld, extra=()):
    cmd = [gcc] + shlex.split(link_flags)
    cmd[cmd.index("-Wl,-Map=" + str(p20 / "ulp_main.map"))] = f"-Wl,-Map={out.with_suffix('.map')}"
    i = cmd.index(str(p20 / "ulp_riscv.ld"))
    cmd[i] = str(src / ld)
    cmd += list(extra) + ["-o", str(out), obj] + rest
    print("+ link", out.name, file=sys.stderr)
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        over = re.search(r"address (0x[0-9a-f]+)", r.stderr)
        if over:
            print(f"LINK-FAIL {out.name}: first over-budget address {over.group(1)} "
                  f"({int(over.group(1), 16)} B needed, pool 7856)", file=sys.stderr)
        else:
            print(r.stderr, file=sys.stderr)
        return False
    return True


def measure(name, elf):
    binpath = elf.with_suffix(".bin")
    subprocess.run(["riscv32-esp-elf-objcopy", "-O", "binary", str(elf), str(binpath)], check=True)
    sec = subprocess.run(["riscv32-esp-elf-size", "-A", str(elf)], capture_output=True, text=True,
                         check=True).stdout
    sizes = {}
    for line in sec.splitlines():
        f = line.split()
        if len(f) == 3 and f[0].startswith("."):
            sizes[f[0]] = int(f[1])
    n = binpath.stat().st_size
    print(f"{name}: bin={n} text={sizes.get('.text')} rodata={sizes.get('.rodata', 0)} "
          f"srodata={sizes.get('.srodata.seed.0', 0)} data={sizes.get('.data', 0)} "
          f"bss={sizes.get('.bss')}", file=sys.stderr)
    return sizes, n


def symbols(elf, tag):
    """nm -S: engine symbols (size-sorted) plus the budget arrays, one file per variant."""
    nm = subprocess.run(["riscv32-esp-elf-nm", "-S", str(elf)], capture_output=True, text=True,
                        check=True).stdout
    out = art / f"p32_{tag}_nm.txt"
    out.write_text(nm)
    sizes = {}
    for line in nm.splitlines():
        f = line.split()
        if len(f) == 4:
            try:
                sizes[f[3]] = int(f[1], 16)
            except ValueError:
                pass
    arrays = ["frm", "ptab", "ptab_lru_reserve", "cmd_ring", "out_ring", "mailbox", "tib", "mem",
              "vm_live", "tsk"]
    miss = [a for a in arrays if a not in sizes]
    print(f"{tag} arrays: " + " ".join(f"{a}={sizes.get(a)}" for a in arrays)
          + (" MISSING=" + ",".join(miss) if miss else " all-present"), file=sys.stderr)
    for s in ("vm_enter", "memcpy", "memset", "vm_switch", "pg_load", "resolve", "rd16_paged",
              "vm_task_init", "word", "find", "mkhdr", "err", "clit", "vm_task_leave",
              "vm_next_ready"):
        print(f"  {tag} {s} = {sizes.get(s, 0)}", file=sys.stderr)
    return sizes


variant = (sys.argv[1] if len(sys.argv) > 1 else "A").upper()
memsz = int(sys.argv[2]) if len(sys.argv) > 2 else 908
defs = VARIANTS[variant]
# GUARDRAIL: MEMSZ/TIBSZ/SD/NTSK are the budget lines, not defaults — dropping any of them makes the
# link cheaper for a machine that is not the one in 4.3 (P29's build script learned this the hard way).
base = [f"-DMEMSZ={memsz}", "-DSD=16", "-DTIBSZ=128", "-DNTSK=3"]

compile_stub(art / "ulp_stubs_only_A.o", ["-DP29_HARNESS_ONLY"])
if not link(art / "p32_control.elf", art / "ulp_stubs_only_A.o", "ulp_p31_diag.ld"):
    raise SystemExit("control link failed")
ctrl, ctxt = measure("control", art / "p32_control.elf")

compile_stub(art / f"ulp_stubs_{variant}.o", base + defs)
fits = link(art / f"p32_{variant}_real.elf", art / f"ulp_stubs_{variant}.o", "ulp_p31.ld")
if not link(art / f"p32_{variant}_diag.elf", art / f"ulp_stubs_{variant}.o", "ulp_p31_diag.ld"):
    raise SystemExit("diag link failed")
sec, n = measure(variant, art / f"p32_{variant}_diag.elf")

text = sec.get(".text", 0) - ctrl.get(".text", 0)
rodata = sec.get(".rodata", 0) - ctrl.get(".rodata", 0)
engine = n - ctxt
print(f"variant {variant}: text={text} rodata={rodata} engine(.bin - control)={engine} "
      f"real-7856-link={'OK' if fits else 'FAIL'}", file=sys.stderr)
total = sum(v for k, v in sec.items() if k in (".text", ".rodata", ".data", ".bss"))
ctrl_total = sum(v for k, v in ctrl.items() if k in (".text", ".rodata", ".data", ".bss"))
design = total - ctrl_total
print(f"region use: {design} of 7856 (harness {ctrl_total}) -> {7856 - design} left", file=sys.stderr)
symbols(art / f"p32_{variant}_diag.elf", variant)
print("OK", file=sys.stderr)
