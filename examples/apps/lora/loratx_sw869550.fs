: TXBUF ( -- ) FRM CFGPTR ! NSSLO 14 >BYTE 0 >BYTE ;
: TX ( -- ) NSSLO 131 >BYTE 0 >BYTE 0 >BYTE 0 >BYTE NSSHI ;
: SETLEN ( n -- )
  NSSLO 140 >BYTE 0 >BYTE 16 >BYTE 0 >BYTE
  >BYTE 1 >BYTE 0 >BYTE NSSHI ;
: IRQ ( -- w ) NSSLO 18 >BYTE 0 >BYTE RD2 NSSHI ;
: WAITX ( -- )
  2000 BEGIN 1- DUP 0= IF DROP EXIT THEN IRQ 1 AND UNTIL DROP ;
: STAT ( -- st ) NSSLO 192 >BYTE RD-BYTE NSSHI ;
: GO ( -- st ) 32 SETLEN TXBUF 32 CLKN NSSHI TX WAITX STAT ;
: RUNLORA ( -- st ) RADIO-INIT 0= IF 0 EXIT THEN GO ;

