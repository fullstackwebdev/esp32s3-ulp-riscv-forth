#!/usr/bin/env python3
"""mkphases.py — emit the ceiling probe: N phases, each filled to near the per-phase window (690 B).

WHY THIS EXISTS (a correction): the first six-phase flagship averaged 268 B per phase, so it was barely bigger
than the 1 536 B control and reported +4 %. That tested a small program, not the claim "paging raises the ceiling".
The claim needs phases AT the window size and enough of them to approach the store's code capacity (~6.3 KB).

Each phase runs six independent scans over the data window with different constants, so every phase is real
arithmetic whose answers are re-derived in Python, and each is sized to fill the window rather than to be small.
A capacity probe, deliberately: it proves a 6 KB program runs, not that a 6 KB program is useful.
"""
import pathlib

PHASES = 9
SCANS_PER_PHASE = 6
OUT = pathlib.Path(__file__).resolve().parent.parent / "tests"

# scan kinds: (name, body-fragment) with a per-phase constant chosen so every phase's numbers differ
def scans(k):
    """Six scans, cell numbers matching their position.

    GUARDRAIL: the cell index must equal the scan's position. Dropping a scan by patching its body left two scans
    writing the SAME cell, so SHOW printed a zero and a doubled value - the arithmetic was right and the report
    was wrong, which reads exactly like a broken scan.
    """
    th = 8 * k + 7
    dv = 3 + (k % 5)
    return [
        ("sum",   "idx @ TAB + C@ z1 @ + z1 !"),
        ("sumsq", "idx @ TAB + C@ DUP * z2 @ + z2 !"),
        ("xor",   "idx @ TAB + C@ z3 @ XOR z3 !"),
        ("max",   "idx @ TAB + C@ z4 @ > IF idx @ TAB + C@ z4 ! THEN"),
        ("gt",    f"idx @ TAB + C@ {th} > IF z5 @ 1 + z5 ! THEN"),
        ("div",   f"idx @ TAB + C@ {dv} /MOD DROP 0= IF z6 @ 1 + z6 ! THEN"),
    ]

def emit(k):
    name = f"ph{k}"
    lines = [f"\\ {name}.fsx — GENERATED by tools/mkphases.py: ceiling probe phase {k}.",
             f"\\ Six scans over the data window (threshold {8*k+7}, divisor {3+(k%5)}), sized to fill the window.",
             "4 CONSTANT DATABLK",
             "CREATE tw 0 ,",
             "CREATE idx 0 ,"] + [f"CREATE z{i} 0 ," for i in range(1, 7)]
    lines += [": TAB ( -- addr ) tw @ ;",
              ": > ( a b -- a>b ) SWAP < ;",
              ": NX ( -- ) idx @ 1 + idx ! ;"]
    for n, (label, body) in enumerate(scans(k), start=1):
        lines += [f": S{n} ( -- ) 0 idx ! BEGIN idx @ 128 < WHILE {body} NX REPEAT ;"]
    lines += [": SHOW ( -- ) " + " ".join(f"z{i} @ ." for i in range(1, 7)) + " ;",
              f": RUN{name.upper()} ( -- ) DATABLK BLOCK tw ! "
              + " ".join(f"S{i}" for i in range(1, 7)) + " SHOW ;",
              f"RUN{name.upper()}"]
    (OUT / f"{name}.fsx").write_text("\n".join(lines) + "\n")

expect = []
for k in range(1, PHASES + 1):
    emit(k)
    th = 8 * k + 7
    dv = 3 + (k % 5)
    data = list(range(128))
    vals = [sum(data), sum(v * v for v in data), 0, max(data),
            sum(1 for v in data if v > th), sum(1 for v in data if v % dv == 0)]
    expect.append(f"ph{k} " + "".join(str(v) for v in vals))
(OUT / "ceiling_expect.txt").write_text("\n".join(expect) + "\n")
print("wrote tests/ceiling_expect.txt")
print(f"mkphases: wrote {PHASES} phases, {SCANS_PER_PHASE} scans each")
