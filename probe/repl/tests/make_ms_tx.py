#!/usr/bin/env python3
"""Generate examples/apps/lora/loratx_ms.fs: loratx.fs retuned to the peer's preset and loaded with our 48 B frame.

    python3 tests/make_ms_tx.py

Generated, never hand-edited, so the frame cannot drift from probe/repl/tests/data/mesh_packet.json.
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[2]
SRC = REPO / "examples/apps/lora/loratx.fs"
OUT = REPO / "examples/apps/lora/loratx_ms.fs"
REF = HERE / "data/mesh_packet.json"


def main():
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--sf", type=int, default=11)
    ap.add_argument("--bw", type=int, default=5)      # RadioLib: 125 kHz = 4, 250 kHz = 5, 500 kHz = 6
    ap.add_argument("--out", default=None)
    ap.add_argument("--ref", default=None, help="alternative reference JSON (frame to transmit)")
    ap.add_argument("--freq", default=None, help="carrier in MHz; default keeps loratx.fs's measured 869.480")
    ap.add_argument("--sync", default="2b", choices=["2b", "2b24", "2b2b", "14"],
                    help="2b = RadioLib private (0x2B,0x44); 2b24 = only the MSB written, second byte left at the chip "
                         "default (what an older firmware's one-byte sync write leaves); 14 = the public pair")
    args = ap.parse_args()
    ref = json.loads(pathlib.Path(args.ref).read_text()) if args.ref else json.loads(REF.read_text())
    frame = bytes.fromhex(ref["frame"])            # header || ciphertext, 48 B
    if not 16 < len(frame) <= 255:
        raise SystemExit(f"reference frame is {len(frame)} B, not a usable LoRa payload")
    if len(frame) % 2:
        # GUARDRAIL: an odd CREATE block leaves HERE odd and R28 then refuses EVERY later definition with ERR_DICT.
        raise SystemExit("frame must be an even byte count")
    src = SRC.read_text()
    # preset: EU_868 slot 0 = 869.4 MHz (0x36566666), SF11, BW 250 kHz = code 0x05, CR 4/5 = 1, LDRO 0
    src = src.replace("  5 C, 134 C, 54 C, 65 C, 153 C, 153 C,", "  5 C, 134 C, 54 C, 86 C, 102 C, 102 C,")
    if args.sync != "2b":
        # GUARDRAIL: only the MSB (0x0740) is the Meshtastic sync byte; 0x0741 is the network-type/control byte whose
        # default is 0x24. A firmware that writes one byte therefore leaves (0x2B,0x24) on the chip, and a receiver
        # configured with RadioLib's 0x44 default never matches it - the two-byte pair has to be measured, not assumed.
        pairs = {"2b24": ("43", "36"), "2b2b": ("43", "43"), "14": ("20", "36")}
        msb, lsb = pairs[args.sync]
        src = src.replace("  5 C, 13 C, 7 C, 64 C, 43 C, 68 C,", f"  5 C, 13 C, 7 C, 64 C, {msb} C, {lsb} C,")
    src = src.replace("  5 C, 139 C, 9 C, 4 C, 1 C, 0 C,",
                      f"  5 C, 139 C, {args.sf} C, {args.bw} C, 1 C, 0 C,")
    head, tail = src.split("CREATE FRM", 1)
    body = tail.split(": TXBUF", 1)
    lines = []
    for i in range(0, len(frame), 6):
        lines.append("  " + " ".join(f"{b} C," for b in frame[i:i + 6]))
    rebuilt = (head + "CREATE FRM\n" + "\n".join(lines) + "\n: TXBUF" + body[1])
    rebuilt = rebuilt.replace(
        "\\ ---- the frame: 16 B Meshtastic header + 10 B protobuf Data",
        "\\ ---- GENERATED by tests/make_ms_tx.py, do not hand-edit.\n"
        "\\ 16 B Meshtastic header + 32 B AES-128-CTR ciphertext,\n"
        "\\ the reference packet in tests/data/mesh_packet.json.")
    rebuilt = rebuilt.replace("GO ( -- st ) 27 SETLEN TXBUF 27 CLKN", f"GO ( -- st ) {len(frame)} SETLEN TXBUF {len(frame)} CLKN")
    for ln in rebuilt.splitlines():
        if len(ln) > 63:
            # GUARDRAIL: this file is delivered by TYPING; a line over 63 B is silently truncated (R21).
            raise SystemExit(f"line longer than 63 B: {ln!r}")
    # name carries every knob that matters, so a probe artefact can never be mistaken for the shipping frame
    tag = f"sf{args.sf}bw{args.bw}sync{args.sync}" + (f"f{args.freq}" if args.freq else "")
    dflt = "loratx_ms.fs" if tag == "sf11bw5sync2b" else f"loratx_ms_{tag}.fs"
    out = pathlib.Path(args.out) if args.out else (REPO / "examples/apps/lora" / dflt)
    out.write_text(rebuilt)
    try:
        shown = out.resolve().relative_to(REPO)
    except ValueError:
        shown = out
    print(f"  wrote {shown} sf{args.sf} bw{args.bw}  frame {len(frame)} B")


if __name__ == "__main__":
    sys.exit(main())
