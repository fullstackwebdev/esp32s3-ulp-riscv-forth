#!/usr/bin/env python3
"""measure_esc.py - how often does the reserved escape byte 0x1D occur in Forth source?

P10's deciding question: if 0x1D appears in real source more than once per 10 KB, it is not a
safe escape and 06-repl.md section 3 must change.

Two corpora:
  1. every *.fs file in the repo (probe/results/P03b-retry-progress/ is excluded: another agent
     owns that directory and it must not be read by this probe)
  2. a synthetic corpus of ~2000 lines written in the style of probe/uforth/boot_min.fs
     (colon definitions, immediate words, backslash comments, GUARDRAIL comments, long lines)

Counts raw 0x1D bytes, reports the rate per kilobyte, and prints the offending lines if any.
"""
import os, sys, random

ESC = 0x1D
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
EXCLUDE = ("probe/results/P03b-retry-progress", "probe/results/P10-repl-host/corpus_synth.fs")

def scan(paths):
    hits, total = [], 0
    for p in paths:
        with open(p, "rb") as f:
            data = f.read()
        total += len(data)
        for i, line in enumerate(data.split(b"\n"), 1):
            n = line.count(bytes([ESC]))
            if n:
                hits.append((os.path.relpath(p, ROOT), i, n, line[:80]))
    return hits, total

def real_files():
    out = []
    for dirpath, dirnames, filenames in os.walk(ROOT):
        rel = os.path.relpath(dirpath, ROOT)
        if any(rel.startswith(e) for e in EXCLUDE):
            continue
        for fn in filenames:
            if fn.endswith(".fs"):
                p = os.path.join(dirpath, fn)
                if any(os.path.relpath(p, ROOT).startswith(e) for e in EXCLUDE):
                    continue
                out.append(p)
    return sorted(out)

# ---- synthetic corpus: boot_min.fs in style, 2000 lines -------------------------------------
PRIMS = "DUP DROP SWAP OVER ROT @ ! C@ C! W@ W! + - * /MOD AND OR XOR INVERT 0= < U< KEY EMIT TYPE".split()
IMM = ["IF", "ELSE", "THEN", "BEGIN", "UNTIL", "AGAIN", "WHILE", "REPEAT", "DO", "LOOP", "+LOOP",
       "[\"]", "LITERAL", ".\"", "\\", "(", "S\""]

def synth(path, lines=2000, seed=1010):
    rnd = random.Random(seed)
    body, i = [], 0
    body.append("\\ corpus_synth.fs - generated by measure_esc.py, not a build input.")
    body.append("\\")
    body.append("\\ Style mimic of boot_min.fs: definitions, immediates, comments, guardrails.")
    while len(body) < lines:
        r = rnd.random()
        if r < 0.08:
            body.append("\\ --- %s ---" % rnd.choice(["system variables", "conditionals", "loops",
                        "number base", "stack juggling", "test helpers", "error paths"]))
        elif r < 0.14:
            body.append("\\ GUARDRAIL: %s" % rnd.choice([
                "BASE pushes the ADDRESS of V_BASE, never its contents",
                "! and W! are ( val addr -- ); addr on TOP",
                "the operand of 0BRANCH is an absolute address",
                "an over-long line must be a named error, never a silent truncation",
                "a definition that fails mid-compile leaves a partial header behind"]))
        elif r < 0.20:
            body.append("\\ " + " ".join(rnd.choice(PRIMS) for _ in range(rnd.randrange(3, 12))))
        elif r < 0.55:
            words = []
            for _ in range(rnd.randrange(2, 9)):
                k = rnd.random()
                if k < 0.55:
                    words.append(rnd.choice(PRIMS))
                elif k < 0.8:
                    words.append(str(rnd.randrange(0, 9999)))
                else:
                    words.append(rnd.choice(["T", "N", "XV", "C99", "FLAG", "COUNT", "BUF"]))
            name = rnd.choice(["T", "N", "SQ", "CNT", "WR", "G", "DN", "BUF", "FLAG", "PAIR"])
            body.append(": %-6s %s ;" % (name, " ".join(words)))
        elif r < 0.68:
            body.append(": %-6s %s %s %s IMMEDIATE" % (rnd.choice(["X", "Y", "Z"]),
                        rnd.choice(["['] BRANCH W, 0 W,", "['] 0BRANCH W, W,", "HERE SWAP W!"]),
                        rnd.choice(["HERE ;", "HERE 2 - ;", "W, ;"]), ""))
        elif r < 0.74:
            body.append(": MSG   .\" %s\" ;" % rnd.choice(["ok", "line dropped", "stack?", "ERR_NO_INPUT"]))
        elif r < 0.80:
            body.append("CREATE %-5s %s" % (rnd.choice(["TAB", "BUF", "REC"]),
                        " ".join("%d C," % rnd.randrange(0, 255) for _ in range(rnd.randrange(2, 8)))))
        elif r < 0.85:
            body.append("%d CONSTANT %s" % (rnd.randrange(0, 65535), rnd.choice(["MAX", "MIN", "SIZE"])))
        elif r < 0.90:
            body.append("( %s )" % " ".join(rnd.choice(PRIMS) for _ in range(4)))
        elif r < 0.95:
            body.append("HEX %X DECIMAL" % rnd.randrange(0, 0xFFFF))
        else:
            body.append("\\ " + "=" * rnd.randrange(10, 60))
        i += 1
    with open(path, "w") as f:
        f.write("\n".join(body) + "\n")
    return path

def report(name, hits, total, nfiles=None):
    kb = total / 1024.0
    per10 = (len_hits / kb * 10) if (kb and (len_hits := sum(h[2] for h in hits))) else 0.0
    print("== %s" % name)
    if nfiles is not None:
        print("   files        : %d" % nfiles)
    print("   bytes        : %d (%.1f KB)" % (total, kb))
    print("   0x1D count   : %d" % sum(h[2] for h in hits))
    print("   0x1D per KB  : %.4f" % (sum(h[2] for h in hits) / kb if kb else 0.0))
    print("   0x1D per 10KB: %.4f  (fail threshold: > 1.0)" % per10)
    for h in hits:
        print("   HIT %s:%d x%d  %r" % h)
    if not hits:
        print("   (no occurrences)")
    print()

def main():
    synth_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "corpus_synth.fs")
    files = real_files()
    hits, total = scan(files)
    report("real Forth source (*.fs in repo, P03b excluded)", hits, total, len(files))

    synth(synth_path)
    hits2, total2 = scan([synth_path])
    report("synthetic corpus (%s)" % os.path.basename(synth_path), hits2, total2, 1)

    report("combined", hits + hits2, total + total2)
    return 0

if __name__ == "__main__":
    sys.exit(main())
