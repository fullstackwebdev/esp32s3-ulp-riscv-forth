#!/usr/bin/env python3
"""mkcapacity.py — generate tests/overlay_capacity.fs from the phase sources.

The test that decides the branch's whole claim: can a paged program exceed the 1544 B single-image size?
It seeds three phase sources into the block store (the same BLOCK/C!/UPDATE/SAVE path an operator uses), then
loads each phase into the overlay area, measures the compiled bytes from HERE, and ASSERTS the total.

Layout:
  blocks 2      empty overlay (the rewind target)
  blocks 8..    phase A   (fill + accumulate)
  blocks 24..   phase B   (scans 1-6)
  blocks 40..   phase C   (scans 7-12)

GUARDRAIL: 6 pokes per line. `NNN W KK + C!` reaches 13 chars for three-digit codes, so even 7 pokes is
89-91 chars and a high line number pushes it past the chip's TIBSZ 96; 6 keeps the worst case at ~80. Original
text: 8 of them is 96 -- past TIBSZ on the chip --
and an over-long line is dropped AFTER it has been partly poked, which seeds a block with holes.
GUARDRAIL: a multi-block phase loads with plain LOAD, never with OVL. OVL rewinds first, so `OVL`-ing the
second block of a phase would delete the first block's definitions.
"""
import math, pathlib, sys

POKES_PER_LINE = 6
HERE = pathlib.Path(__file__).resolve().parent.parent
FIRST_BLOCK = 8
BLOCK_STRIDE = 16
PHASES_SRC = ["a", "b", "c"]




def strip_comments(text):
    """Remove backslash comments before seeding.

    GUARDRAIL: `\\` comments must not travel through blocks. A block is one 128-byte run of characters with no
    line structure, so `\\` swallows everything after it in the chunk - measured as a `TEXT?` error from the word
    "text" inside a comment. Blocks are also ASCII-only; the sources use em dashes in comments, which is why the
    stripping happens here rather than trusting the text.
    """
    out = []
    for line in text.splitlines():
        cut = line.find("\\")
        out.append((line if cut < 0 else line[:cut]).rstrip())
    return " ".join(x for x in out if x) + " "

def chunk_at_spaces(text, size=128):
    """Split into <=size byte chunks, each ending at a SPACE.

    GUARDRAIL: fixed 128-byte cuts are wrong. Successive LOADs concatenate the blocks into one token stream, so
    a token straddling a block boundary is spliced across two blocks and arrives as two halves - measured as
    `ETER?` from a half `LITERAL`. Each chunk therefore ends at the last space that fits, and the block is
    space-padded by the blanking step that precedes the pokes.
    """
    chunks, i = [], 0
    while i < len(text):
        end = min(i + size, len(text))
        if end < len(text):
            cut = text.rfind(" ", i + 1, end)
            if cut > i:
                end = cut + 1
        chunks.append(text[i:end])
        i = end
    return chunks

def pokes(text, block_base):
    out = []
    for start in range(0, len(text), POKES_PER_LINE):
        part = text[start:start + POKES_PER_LINE]
        out.append(" ".join(f"{ord(c)} W {start + i} + C!" for i, c in enumerate(part)))
    return out


def main():
    src = {name: strip_comments((HERE / f"tests/capacity_{name}.fsx").read_text()) for name in PHASES_SRC}
    # GUARDRAIL: bases are computed with a 4-block gap. Hand-picked bases (8/24/40) overlapped phase A, which
    # needs 17 blocks: its last blocks overwrote phase B's first ones and both phases compiled nonsense.
    bases, nxt = {}, 8
    for name in PHASES_SRC:
        bases[name] = nxt
        nxt += len(chunk_at_spaces(src[name])) + 4
    PHASES = [(n, bases[n]) for n in PHASES_SRC]
    lines = []
    add = lines.append
    add("\\ overlay_capacity.fs — GENERATED by tools/mkcapacity.py from tests/capacity_{a,b,c}.fsx. Do not edit.")
    add("\\")
    add("\\ Test 2: does paging a program through the block store exceed the 1 544 B single-image size?")
    add("\\ Three phases are seeded into blocks over the operator's own BLOCK/C!/UPDATE/SAVE path, loaded into the")
    add("\\ sealed overlay area one at a time, and their compiled sizes are measured from HERE and asserted here.")
    add("\\")
    add("\\ GUARDRAIL: a multi-block phase loads with plain LOAD, never OVL: OVL rewinds first, so OVL-ing the")
    add("\\ second block would delete the first block's definitions.")
    add("\\ GUARDRAIL: the phases are seeded by pokes, so this file is large and mechanical. It is generated; the")
    add("\\ reviewable parts are the .fsx sources and this generator.")
    add("")
    add("0 BLOCK CONSTANT W")
    add(": BLKBLANK 0 BEGIN DUP 128 < WHILE 32 OVER W + C! 1 + REPEAT DROP ;")
    add("")
    blocks_used = 0
    for name, base in PHASES:
        text = src[name]
        chunks = chunk_at_spaces(text)
        add(f"\\ ---- phase {name.upper()}: {len(text)} B of source -> {len(chunks)} blocks at {base}")
        for k, chunk in enumerate(chunks):
            blk = base + k
            add(f"{blk} BLOCK DROP  BLKBLANK")
            for line in pokes(chunk, 0):
                add(line)
            add("UPDATE SAVE DROP")
            blocks_used += 1
        blocks_used += 0
    add("")
    add("\\ block 2 is the empty overlay: the rewind target")
    add("2 BLOCK DROP  BLKBLANK  UPDATE SAVE DROP")
    add("")
    add(": RES ( -- ) 7 . ;                 \\ a sealed word that must survive every phase")
    add("SEAL")
    add("HERE . 32 EMIT                     \\ sealed HERE, for the record")
    add("")
    for name, base in PHASES:
        text = src[name]
        nchunks = len(chunk_at_spaces(text))
        parts = [f"{base + k} LOAD" for k in range(nchunks)]
        loads = [" ".join(parts[i:i + 6]) for i in range(0, len(parts), 6)]
        add(f"\\ ---- phase {name.upper()}: rewind, then load every block of the phase")
        add("2 OVL")
        for ln in loads:
            add(ln)
        add(f"HERE . 32 EMIT                     \\ HERE after phase {name.upper()}")
    add("")
    add("\\ ---- the assertion: total compiled across the three phases beats one image")
    add("HERE bh @ - .                      \\ total compiled bytes")
    add("1544 HERE bh @ - < .                \\ -1 when it exceeds the monolith's 1544 B")
    add("")
    add("\\ ---- 50 load/drop cycles must not leak")
    add(": R50 0 BEGIN DUP 50 < WHILE 8 OVL 2 OVL 1 + REPEAT DROP ;")
    add("R50")
    add("HERE bh @ = .                      \\ -1: HERE back at the sealed value")
    add("LATEST bl @ = .                    \\ -1: LATEST back at the sealed value")
    add("RES                                \\ 7: the sealed word still runs")
    add("2 3 + .                            \\ 5: the REPL is intact")
    add("")
    add("\\ ---- the deferred-load hazard must be loud, not silent: PHASE clears the hook, so GO")
    add("\\ before the block has run executes token 0, and EXECUTE of 0 is an error.")
    add("8 PHASE")
    add("GO                                 \\ must be refused by name (last line: an error ends the file)")
    (HERE / "tests/overlay_capacity.fs").write_text("\n".join(lines) + "\n")
    print(f"mkcapacity: wrote tests/overlay_capacity.fs ({len(lines)} lines, {blocks_used} phase blocks)")


if __name__ == "__main__":
    main()
