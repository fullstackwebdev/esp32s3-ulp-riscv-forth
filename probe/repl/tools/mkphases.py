#!/usr/bin/env python3
"""mkphases.py — emit ceiling-probe phases: N phases, each filled toward the per-phase window (~690 B).

Each phase runs six independent scans over the data window with per-phase constants, so every phase is real
arithmetic whose answers are re-derived here and asserted by the tests. A capacity probe, deliberately: it proves a
program of this size RUNS, not that it is useful.

GUARDRAIL: a scan's cell index must equal its position in the list. Dropping a scan by patching its body left two
scans writing the same cell, so the report printed a zero and a doubled value - the arithmetic was right and the
REPORT was wrong, which reads exactly like a broken scan.

Usage: tools/mkphases.py [--count N] [--out DIR]
"""
import argparse
import pathlib

HERE = pathlib.Path(__file__).resolve().parent.parent
SCANS = 6


def scans(k):
    th = 8 * k + 7
    dv = 3 + (k % 5)
    return [
        ("sum",   "idx @ TAB + C@ z1 @ + z1 !"),
        ("sumsq", "idx @ TAB + C@ DUP * z2 @ + z2 !"),
        ("xor",   "idx @ TAB + C@ z3 @ XOR z3 !"),
        ("max",   "idx @ TAB + C@ z4 @ > IF idx @ TAB + C@ z4 ! THEN"),
        ("gt",    f"idx @ TAB + C@ {th} > IF z5 @ 1 + z5 ! THEN"),
        ("div",   f"idx @ TAB + C@ {dv} /MOD DROP 0= IF z6 @ 1 + z6 ! THEN"),
    ]


def emit(out: pathlib.Path, k: int) -> None:
    name = f"ph{k}"
    lines = [f"\\ {name}.fsx — GENERATED by tools/mkphases.py: ceiling-probe phase {k}.",
             f"\\ Six scans over the data window (threshold {8 * k + 7}, divisor {3 + (k % 5)}).",
             "4 CONSTANT DATABLK",
             "CREATE tw 0 ,",
             "CREATE idx 0 ,"]
    lines += [f"CREATE z{i} 0 ," for i in range(1, SCANS + 1)]
    lines += [": TAB ( -- addr ) tw @ ;",
              ": > ( a b -- a>b ) SWAP < ;",
              ": NX ( -- ) idx @ 1 + idx ! ;"]
    for n, (_label, body) in enumerate(scans(k), start=1):
        lines.append(f": S{n} ( -- ) 0 idx ! BEGIN idx @ 128 < WHILE {body} NX REPEAT ;")
    lines.append(": SHOW ( -- ) " + " ".join(f"z{i} @ ." for i in range(1, SCANS + 1)) + " ;")
    lines.append(f": RUN{name.upper()} ( -- ) DATABLK BLOCK tw ! "
                 + " ".join(f"S{i}" for i in range(1, SCANS + 1)) + " SHOW ;")
    lines.append(f"RUN{name.upper()}")
    (out / f"{name}.fsx").write_text("\n".join(lines) + "\n")


def expectation(k: int) -> str:
    th = 8 * k + 7
    dv = 3 + (k % 5)
    data = list(range(128))
    vals = [sum(data), sum(v * v for v in data), 0, max(data),
            sum(1 for v in data if v > th), sum(1 for v in data if v % dv == 0)]
    return f"ph{k} " + "".join(str(v) for v in vals)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--count", type=int, default=9)
    ap.add_argument("--out", default=str(HERE / "tests"))
    args = ap.parse_args()
    out = pathlib.Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    for k in range(1, args.count + 1):
        emit(out, k)
    (out / "ceiling_expect.txt").write_text(
        "\n".join(expectation(k) for k in range(1, args.count + 1)) + "\n")
    print(f"mkphases: {args.count} phases x {SCANS} scans -> {out}")


if __name__ == "__main__":
    main()
