#!/usr/bin/env python3
"""P39: turn src/p39_prelude.fs into src/p39_prelude.h (one C string, one source of truth).

GUARDRAIL: the prelude text is generated from the .fs file rather than typed twice — the host build
that validated the line and the ULP build that runs it must be fed the *same* bytes, or "it works on
the host" stops meaning anything. Every line is a separate C literal so the generated header stays
readable and a diff shows which Forth word changed.
"""
import pathlib

root = pathlib.Path(__file__).resolve().parent
fs = (root / "src" / "p39_prelude.fs").read_text().splitlines()
out = ['/* generated by gen_prelude.py from src/p39_prelude.fs — do not edit */',
       'static const char P39_PRELUDE[] =']
for line in fs:
    esc = line.replace("\\", "\\\\").replace('"', '\\"')
    out.append('    "%s\\n"' % esc)
out.append("    ;")
root.joinpath("src", "p39_prelude.h").write_text("\n".join(out) + "\n")
print("prelude: %d lines, %d bytes of text" % (len(fs), sum(len(l) + 1 for l in fs)))
