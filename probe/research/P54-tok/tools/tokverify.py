#!/usr/bin/env python3
"""tokverify.py — decode two baked images and prove they are the SAME program.

    ./tools/tokverify.py base out/image.h out/names.log p54 out/image_tok.h out/names_tok.log

# GUARDRAIL: this decoder must not share code with the engine's — the P54 bug it caught (a half-used
# code cell making V_HERE a byte late, so every HERE-derived branch target pointed into the middle of a
# cell) is precisely the class a same-code verifier cannot see. It also resolves branch operands to
# (definition, step) because the layout MOVES: comparing absolute operands reports a false mismatch.
#
# The variable-length token idea changes what a compiled body *looks like* in mem[] but must not change
what the engine *does*. This tool is the independent decoder that proves it on the host, before the
image is ever linked: it walks each definition's stream with the encoding named on the command line,
rebuilds the ordered list of executed primitives (with inline operands folded in), and diffs the two
lists definition by definition.

It is deliberately NOT the engine's decoder — a verifier that shares code with the thing it verifies
cannot catch a decoder bug. It reads the cells the way the layout comment says and fails loud on
anything it cannot place.

  base   every token is one 2-byte cell holding the target xt.
  p54    a cell is the target xt (low byte even), or two 1-byte primitive codes, or one code plus a
         0 filler byte: low  = (id << 1) | 1, and the high byte is a second code when its bit 0 is set.
"""
import re
import sys

DICT = 56
P_DOCOL, P_DOVAR, P_DOCON = 0, 1, 2
P_EXIT, P_LIT, P_BRANCH, P_ZBRANCH, P_DO, P_LOOP, P_PLOOP = 3, 4, 5, 6, 7, 8, 9
P_PAUSE, P_FAULT = 64, 65
P_PDOTQ = 56
LEAVING = {P_EXIT, P_BRANCH, P_ZBRANCH, P_LOOP, P_PLOOP, P_PAUSE, P_FAULT}
OPERAND_2 = {P_BRANCH, P_ZBRANCH, P_LOOP, P_PLOOP}


def die(msg):
    sys.exit(f"tokverify: {msg}")


def parse_image(path):
    txt = open(path).read()
    m = re.search(r"generated by uforth -d: (\d+) of (\d+) bytes used", txt)
    if not m:
        die(f"{path}: not a bake dump")
    span, memsz = int(m.group(1)), int(m.group(2))
    data = bytes(int(v, 16) for v in re.findall(r"0x([0-9a-f]{2})", txt[txt.index("{"):]))
    if len(data) != span:
        die(f"{path}: header says {span} B, dump holds {len(data)}")
    return data, span, memsz


def u16(d, a):
    return d[a] | d[a + 1] << 8


def u32(d, a):
    return u16(d, a) | u16(d, a + 2) << 16


def parse_names(path):
    names = {}
    for line in open(path):
        if line.startswith("NAME "):
            m = re.match(r"NAME xt=(\d+) cf=(\d+) imm=(\d+) (.*)\n?$", line)
            xt = int(m.group(1))
            if xt in names:
                die(f"{path}: xt {xt} twice")
            names[xt] = {"cf": int(m.group(2)), "name": m.group(4)}
    if not names:
        die(f"{path}: no NAME lines")
    return names


def load(mode, img, nlog):
    if mode not in ("base", "p54"):
        die(f"mode must be base or p54, not {mode!r}")
    d, hdrtop, memsz = parse_image(img)
    names = parse_names(nlog)
    here, latest = u32(d, 4), u32(d, 8)
    hdrs = {}
    for h in range(latest, hdrtop, 4):
        key = u32(d, h)
        hdrs[(key >> 1) & 0x7FF] = h
    if sorted(hdrs) != sorted(names):
        die(f"{img}: headers and {nlog} name different words")
    for xt in hdrs:
        if u16(d, xt) != names[xt]["cf"]:
            die(f"{img}: xt {xt} code field is {u16(d, xt)}, {nlog} says {names[xt]['cf']}")
    return {"img": img, "d": d, "here": here, "names": names, "mode": mode,
            "xts": sorted(hdrs), "memsz": memsz, "hdrtop": hdrtop, "latest": latest}


def decode_body(im, xt, end):
    """The definition's steps, in execution order, normalised so two encodings compare equal.

    Each step is {"addr", "op", "arg"}:
      op   ("prim", id) for a primitive (however it was encoded) or ("word", name) for a call to a
           colon definition / CREATE / CONSTANT word, which must keep the 2-byte xt form;
      arg  None, ("lit", value), ("operand", address) or ("string", text) for inline data.
    The address is where the engine's `ip` stood when the token was fetched; a branch operand is an
    absolute address, so the comparison resolves it to (definition, step index) later.
    """
    d, names, mode = im["d"], im["names"], im["mode"]
    me = names[xt]["name"]
    cf = u16(d, xt)
    if cf != P_DOCOL:
        return [{"addr": xt, "op": ("codefield", cf), "arg": None}]
    steps, p = [], xt + 2
    while p + 2 <= end:
        cell, addr = u16(d, p), p
        placed = []
        if mode == "p54" and (cell & 1):
            placed.append((cell & 0xFE) >> 1)
            if cell & 0x100:
                placed.append(cell >> 9)
            elif cell >> 8:
                die(f"{me}: cell at {p} has high byte {cell >> 8} set but not flagged as a code")
        else:
            if cell & 1:
                die(f"{me}: token cell at {p} = 0x{cell:04x} has an odd low byte; a 2-byte token "
                    f"is an even xt")
            placed.append(cell)
        for v in placed:
            if mode == "p54" and cell & 1:      # v is a primitive id
                if v in (P_DOCOL, P_DOVAR, P_DOCON):
                    die(f"{me}: primitive id {v} needs w and cannot be a 1-byte code")
                if v >= 128:
                    die(f"{me}: code {v} does not fit in 7 bits")
                op, tcf = ("prim", v), v
            else:                               # v is an xt
                if v not in names:
                    die(f"{me}: token {v} at {p} is not a known xt")
                tcf = names[v]["cf"]
                op = ("codefield", tcf) if tcf in (P_DOCOL, P_DOVAR, P_DOCON) else ("prim", tcf)
                if tcf == P_DOCOL:
                    op = ("word", names[v]["name"])
            steps.append({"addr": addr, "op": op, "arg": None})
        p += 2
        # Inline data belongs to the LAST token placed in the cell: for a pair, only the last one can
        # own inline bytes, and LIT (which does) is always alone because clit() writes its operand as
        # a raw cell that moves V_HERE and closes the free slot.
        last, tcf = steps[-1], steps[-1]["op"][1]
        if last["op"][0] == "word":
            tcf = P_DOCOL
        if tcf == P_LIT:
            last["arg"] = ("lit", u32(d, p))
            p += 4
        elif tcf in OPERAND_2:
            last["arg"] = ("operand", u16(d, p))
            p += 2
        elif tcf == P_PDOTQ:
            n = d[p]
            last["arg"] = ("string", d[p + 1:p + 1 + n].decode("latin-1"))
            p += (n + 2) & ~1
    if p != end:
        die(f"{me}: stream ends at {p}, next definition at {end}")
    return steps


def addr_map(im, bodies):
    """address -> (definition name, step index); the end address of a body maps to len(steps).

    setdefault, not assignment: a paired cell holds TWO steps at ONE address, and a branch to that
    address executes the LOW one first, so the FIRST step at an address is the one a target means.
    """
    m = {}
    for name, steps in bodies:
        for i, st in enumerate(steps):
            m.setdefault(st["addr"], (name, i))
        if steps:
            m.setdefault(steps[-1]["addr"] + 2, (name, len(steps)))
    return m


def packer_facts(im):
    """What the p54 encoding actually bought, read back off the image cells themselves."""
    if im["mode"] != "p54":
        return None
    d = im["d"]
    codes = pairs = lone = xttoks = 0
    for i, xt in enumerate(im["xts"]):
        end = im["xts"][i + 1] if i + 1 < len(im["xts"]) else im["here"]
        if u16(d, xt) != P_DOCOL:
            continue
        p = xt + 2
        while p + 2 <= end:
            cell, tcf = u16(d, p), 0
            if cell & 1:
                codes += 1
                tcf = (cell & 0xFE) >> 1
                if cell & 0x100:
                    codes += 1
                    pairs += 1
                    tcf = cell >> 9
                else:
                    lone += 1
            else:
                xttoks += 1
                tcf = im["names"][cell]["cf"]
            p += 2
            if tcf == P_LIT:
                p += 4
            elif tcf in OPERAND_2:
                p += 2
            elif tcf == P_PDOTQ:
                p += (d[p] + 2) & ~1
    return {"codes": codes, "pairs": pairs, "lone": lone, "xt_tokens": xttoks}


def main():
    if len(sys.argv) != 7:
        die(__doc__)
    a = load(sys.argv[1], sys.argv[2], sys.argv[3])
    b = load(sys.argv[4], sys.argv[5], sys.argv[6])
    print(f"A {a['img']} mode={a['mode']}: code area {a['here']} B, {len(a['xts'])} words")
    print(f"B {b['img']} mode={b['mode']}: code area {b['here']} B, {len(b['xts'])} words")

    # The two images lay the same words out at DIFFERENT xts (that is the saving), so the comparison
    # is by definition NAME in creation order, never by address.
    def bodies(im):
        out = []
        for i, xt in enumerate(im["xts"]):
            end = im["xts"][i + 1] if i + 1 < len(im["xts"]) else im["here"]
            out.append((im["names"][xt]["name"], decode_body(im, xt, end)))
        return out

    ba, bb = bodies(a), bodies(b)
    if [n for n, _ in ba] != [n for n, _ in bb]:
        die("different vocabularies / creation order")
    ma, mb = addr_map(a, ba), addr_map(b, bb)

    def norm(steps, m):
        out = []
        for st in steps:
            arg = st["arg"]
            if arg and arg[0] == "operand":
                if arg[1] not in m:
                    die(f"branch operand {arg[1]} points outside every definition")
                arg = ("target", m[arg[1]])
            out.append((st["op"], arg))
        return out

    bad, steps_total = 0, 0
    for (name, sa), (_, sb) in zip(ba, bb):
        na, nb = norm(sa, ma), norm(sb, mb)
        steps_total += len(na)
        if na != nb:
            bad += 1
            print(f"MISMATCH {name!r}: A has {len(na)} steps, B has {len(nb)}")
            for k in range(max(len(na), len(nb))):
                u = na[k] if k < len(na) else None
                v = nb[k] if k < len(nb) else None
                print(f"   {'  ' if u == v else '**'} A {u}   B {v}")
    print(f"definitions compared: {len(ba)}, steps total {steps_total}, mismatching: {bad}")
    fa, fb = packer_facts(a), packer_facts(b)
    for tag, f in (("A", fa), ("B", fb)):
        if f:
            print(f"{tag} encoding facts: {f['codes']} 1-byte codes, {f['pairs']} of them in paired "
                  f"cells, {f['lone']} lone, {f['xt_tokens']} 2-byte xt tokens")
    if bad:
        die(f"{bad} definition(s) decode differently — the two images are not the same program")
    print("OK: both images decode to the same instruction sequence")
    return 0


if __name__ == "__main__":
    sys.exit(main())
