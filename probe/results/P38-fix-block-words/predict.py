#!/usr/bin/env python3
"""predict.py - P38: the predictions for proof (a), computed here, outside the VM.

The probe's rule is that a fix is proven against a number computed on the host, not against
whatever the engine happens to print. So this script *is* the model: a plain Python nested-if and
a plain Python nested-loop, written from the Forth source shape below rather than from the engine's
behaviour. It emits src/exp_a.fs (the same cases, with the predicted value as a literal) and prints
the table, so the run log can be diffed against a number that existed before the run.

IF model (four nesting levels, leaves 1, 4, 7, ... ):
    LVL ( a b c d -- v )  picks leaf index i = 8d + 4c + 2b + a, value = 3*i + 1
    GUARDRAIL: the flag order is the *stack* order, not the source order — Forth (`a b c d LVL`)
    leaves d on top, so the first IF to run consumes d. P38's first model used 8a+4b+2c+d and
    failed 12 of 16 cases against a correct engine; the disassembly in proof (b) is what settled
    which end of the argument list the outer branch reads (it reads the token that runs first).
LOOP model: four nested BEGIN..UNTIL, 3 iterations each -> 81 innermost executions,
    each adding 1 to ACC, so ACC = 81.
"""
import itertools

N = 3
EXPECTED_LOOP = N ** 4


def leaf(i):
    return 3 * i + 1


def if_fall(indent, space):
    """emit the nested IF/ELSE/THEN that selects leaf `space` (a tuple of flags)."""
    if len(space) == 0:
        i = 0
        return [" " * indent + "%d" % leaf(i)]
    raise AssertionError


def gen_word():
    """`: LVL ( a b c d -- v )` as nested IF..ELSE..THEN, four levels deep, 16 leaves."""
    out = []
    counter = [0]

    def emit(depth, acc):
        pad = "  " * (depth + 1)
        if depth == 4:
            idx = 0
            for bit in acc:
                idx = idx * 2 + bit
            out.append(pad + str(leaf(idx)))
            return
        for bit in (1, 0):
            acc.append(bit)
            if bit == 1:
                out.append(pad + "IF")
                emit(depth + 1, acc)
                out.append(pad + "ELSE")
                acc[-1] = 0
                emit(depth + 1, acc)
                acc[-1] = 1
                out.append(pad + "THEN")
            acc.pop()

    # the inner-most level has no ELSE (leaf either way) so the word is written the way a person
    # would: levels 1..3 branch, level 4 is IF <v> ELSE <v> THEN
    def emit2(depth, acc):
        pad = "  " * (depth + 1)
        if depth == 4:
            # the four flags are already consumed: the leaf is the literal chosen by the path
            idx = 0
            for bit in acc:
                idx = idx * 2 + bit
            out.append(pad + str(leaf(idx)))
            return
        for bit in (1, 0):
            acc.append(bit)
            if bit == 1:
                out.append(pad + "IF")
                emit2(depth + 1, acc)
                out.append(pad + "ELSE")
                acc[-1] = 0
                emit2(depth + 1, acc)
                acc[-1] = 1
                out.append(pad + "THEN")
            acc.pop()

    emit2(0, [])
    return out


def main():
    lines = []
    lines.append("\\ exp_a.fs - P38 (a): GENERATED by predict.py. Do not hand-edit.")
    lines.append("\\ The expected values are Python's nested-if / nested-loop answers, computed before the run.")
    lines.append("CREATE ACC 0 ,")
    for lvl in range(1, 5):
        lines.append("CREATE C%d 0 ," % lvl)
    lines.append(": T ( f -- ) IF .\" PASS\" 10 EMIT EXIT THEN .\" FAIL\" 10 EMIT ;")
    lines.append(": LVL ( a b c d -- v )")
    lines.extend(gen_word())
    lines.append("  ;")
    for a in (0, 1):
        for b in (0, 1):
            for c in (0, 1):
                for d in (0, 1):
                    idx = 8 * d + 4 * c + 2 * b + a
                    want = leaf(idx)
                    lines.append(".\" a-if4-%d%d%d%d \" %d %d %d %d LVL %d = T"
                                 % (a, b, c, d, a, b, c, d, want))
    # four nested BEGIN..UNTIL, N iterations each
    lines.append(": LP ( -- n )  0 ACC !")
    for lvl in range(1, 5):
        lines.append("  %d C%d !" % (N, lvl) if lvl == 1 else "%d C%d !" % (N, lvl))
        lines.append("BEGIN")
    lines.append("  1 ACC @ + ACC !  C4 @ 1- C4 !  C4 @ 0= UNTIL")
    lines.append("  C3 @ 1- C3 !  C3 @ 0= UNTIL")
    lines.append("  C2 @ 1- C2 !  C2 @ 0= UNTIL")
    lines.append("  C1 @ 1- C1 !  C1 @ 0= UNTIL")
    lines.append("  ACC @ ;")
    lines.append('." a-loop4-%d " LP %d = T' % (EXPECTED_LOOP, EXPECTED_LOOP))
    with open("src/exp_a.fs", "w") as f:
        f.write("\n".join(lines) + "\n")

    print("P38 prediction (a): 16 IF/ELSE cases at nesting depth 4, leaf = 3*(8d+4c+2b+a)+1")
    for a, b, c, d in itertools.product((0, 1), repeat=4):
        print("  a-if4-%d%d%d%d -> %d" % (a, b, c, d, leaf(8 * d + 4 * c + 2 * b + a)))
    print("P38 prediction (a): nested BEGIN..UNTIL %d^4 -> ACC = %d" % (N, EXPECTED_LOOP))


if __name__ == "__main__":
    main()
