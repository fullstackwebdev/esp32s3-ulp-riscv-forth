/* GUARDRAIL: BLKPRIM was never defined anywhere. The switch cases, the X-macro entries and the block
 * code were therefore all compiled out while a hand-run host bake passed -DBLKPRIM on the command line —
 * so the baked dictionary and the ULP build disagreed about the primitive table. The symptom was BLOCK
 * resolving on the chip only because the image had it, while the switch had no `case P_BLOCK` and the
 * token fell to `default: err()`. A flag that changes an ORDERING must live in the one file both builds
 * include, never in a command line. Measured cost of the omission: two board sessions chasing "?".
 * GUARDRAIL: BLKSZ lives here too — BLKADR = MEMSZ - BLKSZ is baked into the image as a literal AND
 * computed in the ULP, so a bake with a different BLKSZ puts the buffer where the dictionary expects it
 * to be, and the first fetch overwrites definitions instead of failing. */
/* GUARDRAIL: MEMSZ was 1442 in the baked image ("generated by uforth -d: 1104 of 1442 bytes used") and
 * 2560 by default in the ULP build, because no CMake target defines it. BLKADR = MEMSZ - BLKSZ is a
 * literal in the image AND a computation in the ULP, so the two must be the same number or the buffer
 * lands in the dictionary. Pin it here: one header, both builds. */
/* GUARDRAIL: TIBSZ sizes the input line AND the bake's prelude loader. The prelude has a 93-character
 * line, so a bake at the default 80 refuses to load it ("line too long (93 >= 80)") and leaves the OLD
 * image.h in place — a bake that fails but looks like it succeeded is worse than no bake at all. */
#define TIBSZ 96
#define MEMSZ 1528
