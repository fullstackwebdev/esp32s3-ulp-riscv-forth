CREATE CFGPTR 0 ,
: ADV ( n -- ) CFGPTR @ + CFGPTR ! ;
: ONE ( -- ) CFGPTR @ C@ >BYTE 1 ADV ;
: CLKN ( n -- ) BEGIN DUP WHILE ONE 1- REPEAT DROP ;
: MOVE ( -- ) NSSLO CFGPTR @ C@ 1 ADV CLKN NSSHI ;
: ALL ( n -- ) BEGIN DUP WHILE MOVE 1- REPEAT DROP ;
: RADG ( -- ) 42160 INEN 42168 INEN 42172 INEN ;
: RADSET ( -- ) RADG 1 8 PIN! ;
: RADS2 ( -- ) 1 12 PIN! 0 9 PIN! 0 12 PIN! ;
: RADS3 ( -- ) 2 MS 1 12 PIN! 5 MS ;
: RCFG ( -- ok ) TBL CFGPTR ! 18 ALL 1 ;
: RDY ( -- ) RADG RADSET RADS2 RADS3 1 MS ;
: RADIO-INIT ( -- ok )
  RDY 13 PIN@ 0= 0= IF 0 EXIT THEN RCFG ;

