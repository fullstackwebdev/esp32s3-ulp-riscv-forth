#!/usr/bin/env python3
"""gen_cg.py — turn the switch case bodies into computed-goto labels.

    ./tools/gen_cg.py  ->  src/p33_cases_cg.inc

WHY generated: src/p31_cases.inc is itself generated from uforth.c's original switch, and P30's rule is
that a hand-retyped body makes the next comparison a comparison of two different machines. The label
form must therefore be *derived* from the same text, not retyped.

The transform is the loop contract of vm_enter, spelled out:
    `break;`    -> `goto vm_tail;`    (finished this token; fetch the next one via the loop tail)
    `continue;` -> `goto vm_fetch;`   (a body that already installed the next (w, ip))
`return;` is left alone — it is the same statement in both shapes.

# GUARDRAIL: P_PAREN's body is `while (ti < tl) if (tib[ti++] == ')') break; break;` — TWO breaks on one
# line and only the second one belongs to the switch. A mechanical replacement turns the FIRST into
# `goto vm_tail`, which makes the comment scanner abandon the whole line at the first character that is
# not ')' and hand the remaining source text to interpret(). That is a wrong-answer bug no test row
# catches, so the inner break is restored explicitly below and its count is asserted to be exactly 1.
# GUARDRAIL: every generated body must end in a jump. A body that falls through to the next label makes
# the dispatcher run a primitive nobody asked for — the same silent class as a missing `case`, and the
# reason the writer asserts the jump count instead of trusting the regular expression.
"""
import re
import sys
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
w33 = (root / "src" / "p33_cases.inc").read_text()
INC = '#include "p31_cases.inc"'
if INC not in w33:
    sys.exit("gen_cg: p33_cases.inc no longer includes p31_cases.inc — refusing to guess the layout")
head33, tail33 = w33.split(INC)
src = (root / "src" / "p31_cases.inc").read_text()

# P_PAREN: protect the inner break (see the GUARDRAIL above) by matching its exact tail statement.
PAREN_IN = "if (tib[ti++] == ')') break; break;"
PAREN_OUT = "if (tib[ti++] == ')') break; goto vm_tail;"



def labelise(text):
    # the whole-line P_PAREN case becomes already-final output, and is then immune to the generic pass
    text = text.replace(PAREN_IN, "@@PAREN@@")
    text = re.sub(r"case\s+(P_\w+)\s*:", r"vm_c_\1:", text)
    text = text.replace("break;", "goto vm_tail;")
    text = text.replace("continue;", "goto vm_fetch;")
    return text.replace("@@PAREN@@", PAREN_OUT)


n_paren = src.count(PAREN_IN) + tail33.count(PAREN_IN)
# p33_cases.inc is p31's bodies plus the block/spawn cases appended behind their own -D guards, so the
# generated file is the same three parts in the same order.
body = labelise(src) + "\n" + labelise(tail33)

if n_paren != 1:
    sys.exit(f"gen_cg: P_PAREN's two-break line matched {n_paren} times, expected 1 — refusing to emit")

# every label must be followed, before the next label, by a terminator
labels = re.split(r"(?m)^(vm_c_\w+:)", body)
bad = []
for k in range(1, len(labels), 2):
    chunk = labels[k + 1]
    tail = re.split(r"(?m)^vm_c_\w+:", chunk)[0]
    if not re.search(r"(goto vm_(tail|fetch);|return;|vm_c_\w+:)", tail):
        bad.append(labels[k])
if bad:
    sys.exit("gen_cg: bodies without a terminating jump: " + ", ".join(bad))

out = (
    "/* p33_cases_cg.inc — GENERATED by tools/gen_cg.py from p31_cases.inc and p33_cases.inc. Do not edit.\n"
    " * Computed-goto form of the same bodies: the switch's `break`/`continue` become `goto vm_tail` /\n"
    " * `goto vm_fetch`, so a dispatch costs one indirect jump and one jump out. */\n"
    + head33 + "\n" + body
)
(root / "src" / "p33_cases_cg.inc").write_text(out)
nlab = len(re.findall(r"vm_c_P_\w+:", body))
print(f"gen_cg: {nlab} labels, "
      f"{body.count('goto vm_tail;')} vm_tail, {body.count('goto vm_fetch;')} vm_fetch")
