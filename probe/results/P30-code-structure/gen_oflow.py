#!/usr/bin/env python3
"""P30 variant C/E code generator: split vm_enter's dispatch switch into one noinline function per
primitive, plus a switch whose cases only call them.

Input : src/uforth.c (P29 verbatim) — the `switch (cf) {` ... `}` block inside vm_enter.
Output: src/uforth_prims.inc  (the per-primitive functions, included before vm_enter)
        src/uforth_disp.inc   (the `case P_X: pr_X(); break;` lines, included inside the switch)

Cases whose body changes control flow (`continue`/`return`: EXIT, EXEC, PAUSE, FAULT) cannot become a
void call — they are emitted as `PR_KEEP` lines so vm_enter keeps their original inline body. That is
recorded in RESULT.md rather than papered over.

GUARDRAIL: this generator must read the *P29* switch and not a hand-typed copy — a transcription of 61
bodies is exactly the kind of change that silently alters a primitive and makes the size comparison a
comparison of two different machines.
"""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent
src = (root / "src" / "uforth.c").read_text().splitlines()

# the dispatch switch: from `        switch (cf) {` to the matching `        }` before `if (!ip)`
start = next(i for i, l in enumerate(src) if l.strip() == "switch (cf) {")
end = next(i for i, l in enumerate(src)
           if i > start and l.strip() == "}" and "if (!ip)" in src[i + 1])
# The switch now carries two branches: the out-of-line dispatch (#if) and the original bodies (#else).
# GUARDRAIL: read the #else branch only — scanning both re-derives EXIT/EXEC twice and walks the
# generated function list past the #endif, which is what produced `#endif without #if`.
for i in range(start, end):
    if src[i].strip() == "#else":
        start = i
        break
for i in range(start, end):
    if src[i].strip() == "#endif":
        end = i
        break

chunks, cur = [], None
for line in src[start + 1:end]:
    if re.match(r"^        case ", line):
        if cur:
            chunks.append(cur)
        cur = [line]
    elif cur is not None and not line.strip():
        # GUARDRAIL: a blank line ends the case — the PAUSE/FAULT comment blocks sit between groups
        # and would otherwise be swallowed into WAKE's body (which then swallowed FAULT's `continue`).
        chunks.append(cur); cur = None
    elif cur is not None:
        cur.append(line)
chunks.append(cur)

bodies, calls, kept = [], [], []
for ch in chunks:
    head = ch[0]
    names = re.findall(r"P_([A-Z0-9_]+):", head)
    # GUARDRAIL: most cases carry their body on the `case` line (`case P_DUP: PUSH(TOS); break;`),
    # so the head must be split at the last `case ...:` label or every body comes out empty.
    rest = re.sub(r"case P_[A-Z0-9_]+:", "", head)
    body = ([rest.strip()] if rest.strip() else []) + ch[1:]
    text = "\n".join(body)
    # blank-line separation between case groups is not part of the case
    while body and not body[-1].strip():
        body.pop()
    if "continue" in text or "return" in text:
        kept.append(names[0])
        continue
    if names == ["LOOP", "PLOOP"]:
        for nm, n in (("LOOP", "1"), ("PLOOP", "POP()")):
            b = [l.replace("n = (cf == P_LOOP) ? 1 : POP();", f"n = {n};") for l in body]
            bodies.append((nm, [], b))
            calls.append(nm)
        continue
    if names == ["TICK", "BTICK"]:
        for nm, c in (("TICK", "P_TICK"), ("BTICK", "P_BTICK")):
            b = [l.replace("else if (cf == P_TICK) PUSH(x);",
                           "else if (1) PUSH(x);" if nm == "TICK" else "else if (0) PUSH(x);")
                 for l in body]
            bodies.append((nm, [], b))
            calls.append(nm)
        continue
    bodies.append((names[0], names, body))
    calls.append(names[0])

with open(root / "src" / "uforth_prims.inc", "w") as f:
    f.write("/* P30: generated by gen_oflow.py from P29's dispatch switch — do not hand-edit.\n"
            " * GUARDRAIL: one function per primitive body keeps the code identical to A's inline copy;\n"
            " * noinline is the variable under test, not a rewrite of the primitive. */\n")
    for nm, _, body in bodies:
        while body and not body[-1].strip():
            body.pop()
        if body and body[-1].rstrip().endswith("break;"):
            # the final `break` belongs to the switch, not to the primitive
            body[-1] = body[-1].rstrip()[:-len("break;")].rstrip()
            if not body[-1].strip():
                body.pop()
        f.write(f"static P30_NI void pr_{nm}(void)\n{{\n"
                f"    u32 a, b, n; u8 i, imm; u16 x;\n")
        for l in body:
            f.write(l.replace("        ", "    ", 1) + "\n")
        f.write("}\n")

with open(root / "src" / "uforth_disp.inc", "w") as f:
    f.write("/* P30: generated by gen_oflow.py — the dispatch half. */\n")
    for nm in calls:
        f.write(f"        case P_{nm}: pr_{nm}(); break;\n")

print(f"{len(bodies)} out-of-line primitives, control-flow kept inline: {', '.join(kept)}")
print("dispatched:", ", ".join(calls))
